
CREATE TABLE IF NOT EXISTS public.site_copy (
  key text PRIMARY KEY,
  title text,
  body_md text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text
);

GRANT SELECT ON public.site_copy TO anon, authenticated;
GRANT ALL ON public.site_copy TO service_role;

ALTER TABLE public.site_copy ENABLE ROW LEVEL SECURITY;

CREATE POLICY "site_copy public read" ON public.site_copy FOR SELECT USING (true);

CREATE TRIGGER site_copy_touch_updated_at
  BEFORE UPDATE ON public.site_copy
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

